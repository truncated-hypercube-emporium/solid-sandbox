/// Glyph as 7 rows of 5 bits (bit 4 = leftmost column).
pub fn glyph(c: char) -> [u8; GLYPH_H] {
    let r = rows(c);
    let mut out = [0u8; GLYPH_H];
    for (o, s) in out.iter_mut().zip(r) {
        *o = u8::from_str_radix(s, 2).unwrap_or(0);
    }
    out
}

/// Glyphs for every char a frame can contain, looked up by code point
/// (ASCII directly; anything else through the slow path).
pub struct Font {
    ascii: [[u8; GLYPH_H]; 128],
}

impl Default for Font {
    fn default() -> Self {
        let mut ascii = [[0u8; GLYPH_H]; 128];
        for (i, g) in ascii.iter_mut().enumerate().skip(32) {
            *g = glyph(char::from(i as u8));
        }
        Self { ascii }
    }
}

impl Font {
    #[inline]
    pub fn get(&self, c: char) -> [u8; GLYPH_H] {
        let u = c as u32;
        if (32..128).contains(&u) { self.ascii[u as usize] } else { glyph(c) }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_printable_ascii_char_has_its_own_glyph() {
        let missing = glyph('\u{2603}');
        for u in 33u8..127 {
            let c = char::from(u);
            let rows = super::rows(c);
            assert!(rows.iter().all(|r| r.len() == GLYPH_W && r.chars().all(|b| b == '0' || b == '1')), "{c:?}");
            assert_ne!(glyph(c), missing, "{c:?} falls back to the box");
            assert!(glyph(c).iter().any(|r| *r != 0), "{c:?} has ink");
        }
        assert!(glyph(' ').iter().all(|r| *r == 0));
        // distinct shapes for the default luminance ramp
        let ramp: Vec<_> = " .,:;-~=+*ox#%&@".chars().map(glyph).collect();
        for i in 0..ramp.len() {
            for j in i + 1..ramp.len() {
                assert_ne!(ramp[i], ramp[j]);
            }
        }
        assert_eq!(Font::default().get('A'), glyph('A'));
        assert_eq!(Font::default().get('↓'), glyph('↓'));
    }
}
